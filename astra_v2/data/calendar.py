# Pre-parse to datetime objects (UTC) for fast lookup
_EVENTS: list[datetime] = [
    datetime.strptime(dt_str, "%Y-%m-%d %H:%M").replace(tzinfo=timezone.utc)
    for dt_str in _HIGH_IMPACT_EVENTS
]

# Sort by date for binary search
_EVENTS.sort()

# Build a set of (date, blackout_start_min, blackout_end_min) for O(1) per-bar check
# We store events as sorted list and do a linear scan of a small window.


def is_blackout(now: datetime) -> bool:
    """
    Return True if `now` is within any news blackout window.

    Blackout = [event_time - 90min, event_time + 30min].

    Args:
        now: current UTC datetime (timezone-aware)

    Returns:
        True if trading is blocked.
    """
    if now.tzinfo is None:
        now = now.replace(tzinfo=timezone.utc)

    # Only check events within ±2 hours of `now` (performance optimization)
    for event_time in _EVENTS:
        diff = (now - event_time).total_seconds()
        # diff < -5400 means event is > 90min in the future (too early)
        # diff > 1800  means event is > 30min in the past (already over)
        if diff < -_BLACKOUT_BEFORE.total_seconds():
            continue  # event too far in future — skip (events are sorted, so could break early)
        if diff > _BLACKOUT_AFTER.total_seconds():
            continue  # event too far in past

        # We're within the blackout window
        return True

    return False


def next_event_after(now: datetime) -> Optional[datetime]:
    """Return the next high-impact event after `now`, or None."""
    if now.tzinfo is None:
        now = now.replace(tzinfo=timezone.utc)
    for event_time in _EVENTS:
        if event_time > now:
            return event_time
    return None
